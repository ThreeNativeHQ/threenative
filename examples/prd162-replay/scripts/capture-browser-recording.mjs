import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { chromium } from "@playwright/test";

const url = process.argv[2] ?? "http://127.0.0.1:5193";
const output = path.resolve(process.argv[3] ?? "src/browser-recording.ts");
const browser = await chromium.launch({
  headless: false,
  args: ["--enable-unsafe-webgpu", "--disable-gpu-sandbox", "--ignore-gpu-blocklist"],
});
try {
  const page = await browser.newPage({ viewport: { width: 640, height: 360 } });
  await page.goto(url, { waitUntil: "networkidle" });
  await page.waitForFunction(
    () => globalThis.__PRD162_REPLAY__?.runtimeReady?.() === true,
    undefined,
    { timeout: 30_000 },
  );
  const recording = await page.evaluate(() => globalThis.__PRD162_REPLAY__.recordBrowserRun());
  const serialized = JSON.stringify(recording);
  const sha256 = createHash("sha256").update(serialized).digest("hex");
  const source = `import type { Recording } from "@threenative/core";\n\n// Generated by capture-browser-recording.mjs from a running browser consumer.\nexport const browserRecording = ${JSON.stringify(recording, null, 2)} satisfies Recording;\nexport const browserRecordingSha256 = ${JSON.stringify(sha256)};\n`;
  await mkdir(path.dirname(output), { recursive: true });
  await writeFile(output, source);
  console.info(JSON.stringify({ output, sha256, source: "running-browser-consumer", recording }));
} finally {
  await browser.close();
}
