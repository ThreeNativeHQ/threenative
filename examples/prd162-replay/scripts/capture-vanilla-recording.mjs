import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { chromium } from "@playwright/test";

const url = process.argv[2] ?? "http://127.0.0.1:5193/?vanilla";
const output = path.resolve(process.argv[3] ?? "src/vanilla-browser-recording.ts");
const browser = await chromium.launch({
  headless: false,
  args: ["--enable-unsafe-webgpu", "--disable-gpu-sandbox", "--ignore-gpu-blocklist"],
});
try {
  const page = await browser.newPage({ viewport: { width: 640, height: 360 } });
  await page.goto(url, { waitUntil: "networkidle" });
  await page.waitForFunction(() => globalThis.__PRD162_VANILLA__ !== undefined, undefined, {
    timeout: 30_000,
  });
  await page.keyboard.down("KeyD");
  const recording = await page.evaluate(() => globalThis.__PRD162_VANILLA__.run());
  await page.keyboard.up("KeyD");
  const serialized = JSON.stringify(recording);
  const sha256 = createHash("sha256").update(serialized).digest("hex");
  const source = `// Generated by capture-vanilla-recording.mjs from the running plain-Three.js control arm.\nexport const vanillaBrowserRecording = ${JSON.stringify(recording, null, 2)};\nexport const vanillaBrowserRecordingSha256 = ${JSON.stringify(sha256)};\n`;
  await mkdir(path.dirname(output), { recursive: true });
  await writeFile(output, source);
  console.info(
    JSON.stringify({ output, sha256, source: "running-browser-control-arm", recording }),
  );
} finally {
  await browser.close();
}
